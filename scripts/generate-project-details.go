// Code generator for project details.
// Usage: go run scripts/generate-project-details.go
// Or: make generate

package main

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"strings"
	"text/template"
)

type ProjectDetails struct {
	Name        string   `json:"name"`
	Slug        string   `json:"slug"`
	Description string   `json:"description"`
	Modules     []string `json:"modules"`
	Git         struct {
		Module string `json:"module"`
		Remote string `json:"remote"`
	} `json:"git"`
}

const goTemplate = `// Code generated by scripts/generate-project-details.go from ../project-details. DO NOT EDIT.

package project

const (
	// Name is the project name
	Name = {{ printf "%q" .Name }}

	// Slug is the URL-friendly version
	Slug = {{ printf "%q" .Slug }}

	// Description describes the project
	Description = {{ printf "%q" .Description }}

	// ModulePath is the Go module path for this gateway repo
	ModulePath = {{ printf "%q" .ModulePath }}

	// BinaryName is the output binary name
	BinaryName = {{ printf "%s-gateway" .Slug | printf "%q" }}
)

// Version is set at build time
var Version = "dev"
`

const makefileTemplate = `# Code generated by scripts/generate-project-details.go from ../project-details. DO NOT EDIT.

BINARY_NAME={{ .Slug }}-gateway
`

const projectDetailsURL = "https://raw.githubusercontent.com/nevaria-ai/nevaria/refs/heads/main/project-details/project-name-template.json"

func main() {
	// Fetch project details from GitHub
	resp, err := http.Get(projectDetailsURL)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error fetching project details: %v\n", err)
		os.Exit(1)
	}
	defer func() { _ = resp.Body.Close() }()

	if resp.StatusCode != http.StatusOK {
		fmt.Fprintf(os.Stderr, "Error fetching project details: HTTP %d\n", resp.StatusCode)
		os.Exit(1)
	}

	data, err := io.ReadAll(resp.Body)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading response: %v\n", err)
		os.Exit(1)
	}

	var details ProjectDetails
	if err := json.Unmarshal(data, &details); err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing project details: %v\n", err)
		os.Exit(1)
	}

	// Gateway's module path: org-base + /gateway
	modulePath := details.Git.Module + "/gateway"

	// Create template data
	templateData := struct {
		ProjectDetails
		ModulePath string
	}{
		ProjectDetails: details,
		ModulePath:     modulePath,
	}

	// Generate Go code
	tmpl, err := template.New("details").Parse(goTemplate)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing Go template: %v\n", err)
		os.Exit(1)
	}

	var buf strings.Builder
	if err := tmpl.Execute(&buf, templateData); err != nil {
		fmt.Fprintf(os.Stderr, "Error executing Go template: %v\n", err)
		os.Exit(1)
	}

	// Write to internal/project/details.go
	if err := os.WriteFile("internal/project/details.go", []byte(buf.String()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing details.go: %v\n", err)
		os.Exit(1)
	}

	// Generate Makefile include
	makeTmpl, err := template.New("makefile").Parse(makefileTemplate)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing Makefile template: %v\n", err)
		os.Exit(1)
	}

	var makeBuf strings.Builder
	if err := makeTmpl.Execute(&makeBuf, templateData); err != nil {
		fmt.Fprintf(os.Stderr, "Error executing Makefile template: %v\n", err)
		os.Exit(1)
	}

	// Write to .makedefs
	if err := os.WriteFile(".makedefs", []byte(makeBuf.String()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing .makedefs: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated internal/project/details.go and .makedefs from %s\n", projectDetailsURL)
}
